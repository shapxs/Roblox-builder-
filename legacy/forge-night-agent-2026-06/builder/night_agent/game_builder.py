@dataclass
class BuildResult:
    """Result of a game build."""
    concept_id: str
    name: str
    build_path: str
    scripts_generated: int
    status: str  # success | failed | needs_improvement
    council_score: float = 0.0
    improvements: List[str] = field(default_factory=list)


class GameBuilder:
    """Builds Roblox games from concepts using Qwen3-Coder-Next."""
    
    def __init__(self):
        # Get project root from script location
        script_dir = os.path.dirname(os.path.abspath(__file__))
        self.projects_path = os.path.join(script_dir, "..", "projects", "roblox")
        os.makedirs(self.projects_path, exist_ok=True)
    
    def build(self, concept: GameConcept) -> BuildResult:
        """Build a complete Roblox game from a concept."""
        print(f"\n{'='*60}")
        print(f"BUILDING GAME: {concept.name}")
        print(f"Genre: {concept.genre} | Theme: {concept.theme}")
        print(f"Core Mechanic: {concept.core_mechanic[:80]}...")
        print("="*60)
        
        # Create project directory
        safe_name = concept.name.lower().replace(" ", "_")
        build_path = os.path.join(self.projects_path, safe_name)
        os.makedirs(build_path, exist_ok=True)
        
        # Generate all game files
        self._generate_game_design_document(concept, build_path)
        self._generate_monetization_plan(concept, build_path)
        self._generate_assets_needed(concept, build_path)
        self._generate_scripts(concept, build_path)
        
        result = BuildResult(
            concept_id=concept.concept_id,
            name=concept.name,
            build_path=build_path,
            scripts_generated=self._count_lua_scripts(build_path),
            status="success"
        )
        
        print(f"✓ Game built at: {build_path}")
        print(f"✓ Scripts generated: {result.scripts_generated}")
        
        return result
    
